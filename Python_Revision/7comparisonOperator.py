# --------------------------------------------------------- 
print("-"*60)
print("3. COMPARISON OPERATORS")
print("-"*60)
print()

a = 23
print(f"Value of a : {a}")
b = 43
print(f"Value of b : {b}")
print()

print(f"1. Equal to : a == b")
print(f"{a == b}")
print()

print(f"2. Not Equal to : a != b")
print(f"{a != b}")
print()

print(f"3. Greater than : a > b")
print(f"{a > b}")
print()

print(f"4. Less than : a < b")
print(f"{a < b}")
print()

print(f"5. Greater than or Equal to : a >= b")
print(f"{a >= b}")
print()

print(f"6. Less than or Equal to : a <= b")
print(f"{a <= b}")
print()

print(f"7. Chained Comparison : 10 < a < 30")
print(f"{10 < a < 30}")
print()

print(f"8. Chained Comparison : 10 < a > 5")
print(f"{10 < a > 5}")
